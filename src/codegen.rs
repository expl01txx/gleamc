//! C code generation for the parsed Gleam subset.
//!
//! Generated programs use tagged values and reference-counted heap objects.
//! The runtime is embedded in this crate so a generated project has no
//! dependencies beyond a C11 compiler and the POSIX C library.

use crate::ast::*;
use crate::bit_array::{SegmentKind, SegmentOptions};
use crate::dependencies;
use crate::typechecker::{self, TypeCheckError};
use std::collections::HashMap;
use std::fmt;
use std::fs;
use std::io;
use std::path::Path;

pub const RUNTIME_HEADER: &str = include_str!("runtime/gleam_runtime.h");
pub const RUNTIME_SOURCE: &str = include_str!("runtime/gleam_runtime.c");

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodegenError {
    pub message: String,
    pub span: Span,
    /// 1-based line number (only when the source text is available).
    pub line: Option<u32>,
    /// 1-based column number (only when the source text is available).
    pub col: Option<u32>,
}

impl CodegenError {
    fn new(message: impl Into<String>, span: Span) -> Self {
        Self {
            message: message.into(),
            span,
            line: None,
            col: None,
        }
    }
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match (self.line, self.col) {
            (Some(line), Some(col)) => write!(f, "{line}:{col}: C codegen: {}", self.message),
            _ => write!(f, "C codegen at byte {}: {}", self.span.start, self.message),
        }
    }
}

impl std::error::Error for CodegenError {}

/// Parse, type check and translate one Gleam module to a C source file.
pub fn translate(source: &str) -> Result<String, CompileError> {
    let module = crate::parse(source).map_err(CompileError::Parse)?;
    typechecker::typecheck_source(source, &module).map_err(CompileError::Type)?;
    generate_c(&module).map_err(CompileError::Codegen)
}

/// Parse, type check and translate one Gleam module to a single
/// self-contained C source file with the runtime embedded. The result has no
/// dependencies beyond a C11 compiler and can be built directly:
/// `cc -std=c11 file.c -o program`.
pub fn translate_standalone(source: &str) -> Result<String, CompileError> {
    let module = crate::parse(source).map_err(CompileError::Parse)?;
    typechecker::typecheck_source(source, &module).map_err(CompileError::Type)?;
    generate_c_standalone(&module).map_err(CompileError::Codegen)
}

/// Translate a parsed module to a single self-contained C source file with
/// the runtime header and implementation embedded.
pub fn generate_c_standalone(module: &Module) -> Result<String, CodegenError> {
    let mut output = generate_c(module)?;
    // Replace the prologue (comment + runtime include) with an inlined copy
    // of the header so the file has no external dependencies.
    output = output.replacen(
        "/* Generated by gleam-parser. Requires C11 and a POSIX system. */\n#include \"gleam_runtime.h\"\n",
        &format!(
            "/* Generated by gleamc: self-contained C11 (runtime embedded). Compile with: cc -std=c11 file.c -o program */\n#define _POSIX_C_SOURCE 200809L\n{RUNTIME_HEADER}"
        ),
        1,
    );
    output.push_str("\n// ---- embedded runtime ----\n");
    output.push_str(&runtime_body());
    Ok(output)
}

/// `RUNTIME_SOURCE` with its preamble (comment, `_POSIX_C_SOURCE` define and
/// `#include \"gleam_runtime.h\"`) removed, for embedding after an inlined
/// copy of the header in a standalone C file.
fn runtime_body() -> String {
    match RUNTIME_SOURCE.split_once("#include \"gleam_runtime.h\"") {
        Some((_, rest)) => rest.trim_start().to_string(),
        None => RUNTIME_SOURCE.to_string(),
    }
}

/// Translate a parsed module. The output includes a C `main` wrapper when the
/// Gleam module defines `main`.
pub fn generate_c(module: &Module) -> Result<String, CodegenError> {
    Compiler::new(module)?.compile()
}

/// Type check the module, then write `main.c`, `gleam_runtime.c`, and
/// `gleam_runtime.h` into a directory.
pub fn write_c_project(
    source: &str,
    module: &Module,
    directory: impl AsRef<Path>,
) -> Result<(), ProjectError> {
    typechecker::typecheck_source(source, module).map_err(ProjectError::Type)?;
    let c_source = match generate_c(module) {
        Ok(c) => c,
        Err(mut error) => {
            let (line, col) = error.span.line_col(source);
            error.line = Some(line);
            error.col = Some(col);
            return Err(ProjectError::Codegen(error));
        }
    };
    write_generated_project(&c_source, directory.as_ref()).map_err(ProjectError::Io)
}

pub(crate) fn write_generated_project(c_source: &str, directory: &Path) -> io::Result<()> {
    fs::create_dir_all(directory)?;
    fs::write(directory.join("main.c"), c_source)?;
    fs::write(directory.join("gleam_runtime.c"), RUNTIME_SOURCE)?;
    fs::write(directory.join("gleam_runtime.h"), RUNTIME_HEADER)?;
    Ok(())
}

#[derive(Debug)]
pub enum CompileError {
    Parse(ParseError),
    Type(TypeCheckError),
    Codegen(CodegenError),
}

impl fmt::Display for CompileError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Parse(error) => error.fmt(f),
            Self::Type(error) => error.fmt(f),
            Self::Codegen(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for CompileError {}

#[derive(Debug)]
pub enum ProjectError {
    Type(TypeCheckError),
    Codegen(CodegenError),
    Io(io::Error),
}

impl fmt::Display for ProjectError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Type(error) => error.fmt(f),
            Self::Codegen(error) => error.fmt(f),
            Self::Io(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for ProjectError {}

#[derive(Clone)]
struct ConstructorInfo {
    fields: Vec<RecordField>,
}

#[derive(Clone)]
struct FunctionInfo {
    c_name: String,
    arity: usize,
    labels: Vec<Option<String>>,
}

#[derive(Default)]
struct Scope {
    locals: Vec<String>,
}

struct Compiler<'a> {
    module: &'a Module,
    constructors: HashMap<String, ConstructorInfo>,
    functions: HashMap<String, FunctionInfo>,
    imports: HashMap<String, String>,
    unqualified: HashMap<String, (String, String)>,
    constants: Vec<String>,
    visible: HashMap<String, String>,
    scopes: Vec<Scope>,
    counter: usize,
    extra_functions: String,
    /// C name of the function currently being compiled, if any.
    current_fn: Option<String>,
    /// True while compiling an expression in tail position inside a
    /// function that is being compiled with tail-call optimization.
    tail_mode: bool,
    /// C names of the current function's parameter bindings (TCO only).
    param_locals: Vec<String>,
    /// Case subjects (one vec per enclosing case) that are still live and
    /// must be released before a tail jump. TCO only.
    live_case_subjects: Vec<Vec<String>>,
}

/// Outcome of compiling an expression in tail position: either a value was
/// produced, or the code path ends in a tail jump (and never falls through).
enum TailOutcome {
    Jumped,
    Value(String),
}

impl<'a> Compiler<'a> {
    fn new(module: &'a Module) -> Result<Self, CodegenError> {
        let mut constructors = HashMap::new();
        let mut functions = HashMap::new();
        let mut imports = HashMap::new();
        let mut unqualified = HashMap::new();
        let mut constants = Vec::new();

        for definition in &module.definitions {
            match definition {
                Definition::Type(ty) => {
                    if let TypeDefKind::Record(variants) = &ty.kind {
                        for variant in variants {
                            if constructors
                                .insert(
                                    variant.name.clone(),
                                    ConstructorInfo {
                                        fields: variant.fields.clone(),
                                    },
                                )
                                .is_some()
                            {
                                return Err(CodegenError::new(
                                    format!("duplicate constructor `{}`", variant.name),
                                    ty.span,
                                ));
                            }
                        }
                    }
                }
                Definition::Fn(function) => {
                    let c_name = format!("gleam_fn_{}", function.name);
                    functions.insert(
                        function.name.clone(),
                        FunctionInfo {
                            c_name,
                            arity: function.args.len(),
                            labels: function
                                .args
                                .iter()
                                .map(|arg| arg.label.clone().or_else(|| Some(arg.name.clone())))
                                .collect(),
                        },
                    );
                }
                Definition::Constant(constant) => constants.push(constant.name.clone()),
                Definition::Import(import) => {
                    let module_name = import.module.join("/");
                    let alias = import
                        .alias
                        .clone()
                        .or_else(|| import.module.last().cloned())
                        .unwrap();
                    if !alias.starts_with('_') {
                        imports.insert(alias, module_name.clone());
                    }
                    for item in &import.unqualified {
                        let (name, local, is_type) = item.names();
                        if !is_type {
                            unqualified.insert(local.into(), (module_name.clone(), name.into()));
                        }
                    }
                }
            }
        }

        // Built-in constructors from the standard library. `Eq`, `Lt`, and
        // `Gt` are the variants of `gleam/order.Order`, returned by
        // `string.compare`; `InvalidBase` is the error of `gleam/int` base
        // conversion functions; `Continue` and `Stop` are the variants of
        // `gleam/list.ContinueOrStop`, used by `list.fold_until`.
        for (name, fields) in [("Ok", 1), ("Error", 1), ("Some", 1), ("None", 0),
                               ("Eq", 0), ("Lt", 0), ("Gt", 0), ("InvalidBase", 0),
                               ("Continue", 1), ("Stop", 1)] {
            constructors.entry(name.into()).or_insert_with(|| ConstructorInfo {
                fields: (0..fields)
                    .map(|_| RecordField {
                        label: None,
                        name: None,
                        type_annotation: TypeAnnotation::Named {
                            module: None,
                            name: "a".into(),
                            args: Vec::new(),
                        },
                    })
                    .collect(),
            });
        }

        Ok(Self {
            module,
            constructors,
            functions,
            imports,
            unqualified,
            constants,
            visible: HashMap::new(),
            scopes: Vec::new(),
            counter: 0,
            current_fn: None,
            tail_mode: false,
            param_locals: Vec::new(),
            live_case_subjects: Vec::new(),
            extra_functions: String::new(),
        })
    }

    fn compile(mut self) -> Result<String, CodegenError> {
        let mut declarations = String::new();
        let mut definitions = String::new();
        let functions: Vec<&FnDef> = self
            .module
            .definitions
            .iter()
            .filter_map(|definition| match definition {
                Definition::Fn(function) => Some(function),
                _ => None,
            })
            .collect();

        for function in &functions {
            let info = &self.functions[&function.name];
            declarations.push_str(&format!(
                "static GValue {}(GClosure *, GValue *, size_t);\n",
                info.c_name
            ));
        }
        declarations.push('\n');
        let mut constructors: Vec<_> = self.constructors.iter().collect();
        constructors.sort_unstable_by_key(|(tag, _)| tag.as_str());
        for (tag, info) in constructors {
            if info.fields.is_empty() {
                continue;
            }
            let name = format!("gleam_ctor_{tag}");
            declarations.push_str(&format!(
                "static GValue {name}(GClosure *, GValue *, size_t);\n"
            ));
            definitions.push_str(&format!(
                "static GValue __attribute__((unused)) {name}(GClosure *closure, GValue *args, size_t argc) {{\n  (void)closure;\n  if (argc != {}) g_panic(\"incorrect argument count\", __FILE__, __LINE__);\n  GValue fields[{}];\n",
                info.fields.len(), info.fields.len()
            ));
            for index in 0..info.fields.len() {
                definitions.push_str(&format!("  fields[{index}] = g_retain(args[{index}]);\n"));
            }
            definitions.push_str(&format!(
                "  return g_record({}, {}, fields);\n}}\n\n",
                c_string(tag), info.fields.len()
            ));
        }

        for function in functions {
            definitions.push_str(&self.compile_function(function)?);
        }

        let mut constants = String::new();
        for name in &self.constants {
            constants.push_str(&format!("static GValue gleam_const_{name};\n"));
        }
        if !self.constants.is_empty() {
            constants.push_str("\nstatic void gleam_init_constants(void) {\n");
            let constants_to_compile =
                dependencies::constants(self.module).map_err(|constant| {
                    CodegenError::new(
                        format!("cyclic constant `{}`", constant.name),
                        constant.span,
                    )
                })?;
            for constant in constants_to_compile {
                let value =
                    self.compile_constant(&constant.value, constant.span, &mut constants)?;
                constants.push_str(&format!("  gleam_const_{} = {value};\n", constant.name));
            }
            constants.push_str("}\n\n");
        }

        let has_main = self.functions.contains_key("main");
        let mut output = String::from(
            "/* Generated by gleam-parser. Requires C11 and a POSIX system. */\n#include \"gleam_runtime.h\"\n#include <limits.h>\n\n",
        );
        output.push_str(&constants);
        output.push_str(&declarations);
        output.push_str(&self.extra_functions);
        output.push_str(&definitions);
        if has_main {
            output.push_str(
                "int main(int argc, char **argv) {\n  GValue gleam_result;\n",
            );
            if !self.constants.is_empty() {
                output.push_str("  gleam_init_constants();\n");
            }
            output.push_str("  gleam_init_cli_args(argc, argv);\n");
            output.push_str(
                "  gleam_result = gleam_fn_main(NULL, NULL, 0);\n  g_release(gleam_result);\n",
            );
            for name in &self.constants {
                output.push_str(&format!("  g_release(gleam_const_{name});\n"));
            }
            output.push_str("  return 0;\n}\n");
        }
        Ok(output)
    }

    fn compile_function(&mut self, function: &FnDef) -> Result<String, CodegenError> {
        let info = self.functions[&function.name].clone();
        self.visible.clear();
        self.scopes.clear();
        self.scopes.push(Scope::default());

        if let Some(external) = function.c_externals().next() {
            if !is_c_identifier(&external.function) {
                return Err(CodegenError::new(
                    "invalid C external function name",
                    function.span,
                ));
            }
            return Ok(format!(
                "extern GValue {symbol}(GValue *, size_t);\nstatic GValue {name}(GClosure *closure, GValue *args, size_t argc) {{\n  (void)closure;\n  if (argc != {arity}) g_panic(\"incorrect argument count\", __FILE__, __LINE__);\n  return {symbol}(args, argc);\n}}\n\n",
                symbol = external.function, name = info.c_name, arity = info.arity,
            ));
        }
        if matches!(function.body.expr, Expr::Block(ref body) if body.is_empty()) {
            return Err(CodegenError::new(
                "function has no implementation for the C target",
                function.span,
            ));
        }

        let mut body = format!(
            "static GValue {}(GClosure *closure, GValue *args, size_t argc) {{\n  (void)closure;\n  (void)args;\n",
            info.c_name
        );
        body.push_str(&format!(
            "  if (argc != {}) g_panic(\"incorrect argument count\", __FILE__, __LINE__);\n",
            function.args.len()
        ));
        for (index, arg) in function.args.iter().enumerate() {
            let name = self.temp();
            body.push_str(&format!("  GValue {name} = g_retain(args[{index}]);\n"));
            self.visible.insert(arg.name.clone(), name.clone());
            self.param_locals.push(name.clone());
            self.scopes.last_mut().unwrap().locals.push(name);
        }
        if Self::has_tail_self_call(&function.body, &function.name) {
            // Tail-call optimization: the body is compiled inside an infinite
            // loop and every direct self-recursive call in tail position
            // becomes a jump back to the top of the loop (rebinding the
            // parameters) instead of a nested C call. Deep recursion then
            // uses constant stack space.
            body.push_str("  for (;;) {\n    gleam_top:\n    {\n");
            self.current_fn = Some(info.c_name.clone());
            self.tail_mode = true;
            let outcome = self.gen_expr_tail(&function.body, &mut body)?;
            self.tail_mode = false;
            self.current_fn = None;
            match outcome {
                TailOutcome::Value(result) => {
                    body.push_str(&format!("      GValue gleam_return = {result};\n"));
                }
                // Unreachable: every path ends in a tail jump.
                TailOutcome::Jumped => {
                    body.push_str("      GValue gleam_return = g_nil();\n");
                }
            }
            self.release_scope(&mut body);
            body.push_str("      return gleam_return;\n    }\n  }\n}\n\n");
        } else {
            let result = self.gen_expr(&function.body, &mut body)?;
            body.push_str(&format!("  GValue gleam_return = {result};\n"));
            self.release_scope(&mut body);
            body.push_str("  return gleam_return;\n}\n\n");
        }
        self.param_locals.clear();
        self.visible.clear();
        self.scopes.clear();
        Ok(body)
    }

    /// True if `expr` contains a direct self-recursive call in tail position
    /// (through blocks and case clauses). Such functions are compiled with
    /// tail-call optimization.
    fn has_tail_self_call(expr: &Expression, name: &str) -> bool {
        match &expr.expr {
            Expr::Call(call) => matches!(&call.fun.expr, Expr::Var(fun) if fun == name),
            Expr::Block(statements) => statements
                .last()
                .is_some_and(|last| Self::has_tail_self_call(last, name)),
            Expr::Case(case) => case
                .clauses
                .iter()
                .any(|clause| Self::has_tail_self_call(&clause.expression, name)),
            _ => false,
        }
    }

    fn compile_constant(
        &mut self,
        value: &ConstValue,
        span: Span,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        match value {
            ConstValue::Int(value) => Ok(format!("g_int({})", self.integer(value, span)?)),
            ConstValue::Float(value) => Ok(format!("g_float({})", self.float(value))),
            ConstValue::String(value) => Ok(c_string_value(value)),
            ConstValue::Bool(value) => Ok(format!("g_bool({})", *value as u8)),
            ConstValue::Nil => Ok("g_nil()".into()),
            ConstValue::Var(name) => {
                if self.constants.contains(name) {
                    Ok(format!("g_retain(gleam_const_{name})"))
                } else {
                    Err(CodegenError::new(format!("unknown constant `{name}`"), span))
                }
            }
            ConstValue::List { elements, spread } => {
                let mut result = match spread {
                    Some(rest) => self.compile_constant(rest, span, out)?,
                    None => "g_list_empty()".into(),
                };
                for element in elements.iter().rev() {
                    result = format!(
                        "g_list_prepend({}, {result})",
                        self.compile_constant(element, span, out)?
                    );
                }
                Ok(result)
            }
            ConstValue::Tuple(elements) => {
                if elements.is_empty() {
                    return Ok("g_tuple(0, NULL)".into());
                }
                let values = elements
                    .iter()
                    .map(|element| self.compile_constant(element, span, out))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(format!(
                    "g_tuple({}, (GValue[]){{{}}})",
                    values.len(),
                    values.join(", ")
                ))
            }
            ConstValue::Qualified { module, name } => Err(CodegenError::new(
                format!("unknown module constant `{module}.{name}`"),
                span,
            )),
            ConstValue::Concat(left, right) => {
                let left = self.compile_constant(left, span, out)?;
                let right = self.compile_constant(right, span, out)?;
                let temp = self.temp();
                out.push_str(&format!(
                    "  GValue {temp}_left = {left};\n  GValue {temp}_right = {right};\n  GValue {temp} = g_string_concat({temp}_left, {temp}_right);\n  g_release({temp}_left);\n  g_release({temp}_right);\n",
                ));
                Ok(temp)
            }
            ConstValue::Constructor(reference, args) => {
                let info = self.constructor(reference, span)?;
                if args.len() != info.fields.len() {
                    return Err(CodegenError::new(
                        format!(
                            "`{}` expects {} field(s), but the constant has {}",
                            reference.name,
                            info.fields.len(),
                            args.len()
                        ),
                        span,
                    ));
                }
                let labels = info.labels();
                let mut evaluated = Vec::with_capacity(args.len());
                for arg in args {
                    evaluated.push((
                        arg.label.clone(),
                        self.compile_constant(&arg.value, span, out)?,
                    ));
                }
                let values = order_arguments(evaluated, &labels, span)?;
                Ok(format!(
                    "g_record({}, {}, {})",
                    c_string(&reference.name),
                    values.len(),
                    c_arguments(&values),
                ))
            }
            ConstValue::BitArray(array) => self.gen_bits(
                array,
                span,
                |value| matches!(value, ConstValue::String(_)),
                |compiler, value, out| {
                    let expression = compiler.compile_constant(value, span, out)?;
                    let temp = compiler.temp();
                    out.push_str(&format!("  GValue {temp} = {expression};\n"));
                    Ok(temp)
                },
                out,
            ),
        }
    }

    fn temp(&mut self) -> String {
        let name = format!("g_{}", self.counter);
        self.counter += 1;
        name
    }

    fn release_scope(&mut self, output: &mut String) {
        if let Some(scope) = self.scopes.pop() {
            for local in scope.locals.iter().rev() {
                output.push_str(&format!("  g_release({local});\n"));
            }
        }
    }

    /// Evaluate an expression and materialize its result in a named
    /// temporary. The returned name owns one reference that the caller is
    /// responsible for releasing; splicing the same name several times is
    /// therefore always safe.
    fn gen_expr(&mut self, expression: &Expression, out: &mut String) -> Result<String, CodegenError> {
        let inner = self.gen_expr_inner(expression, out)?;
        let temp = self.temp();
        out.push_str(&format!("  GValue {temp} = {inner};\n"));
        Ok(temp)
    }

    fn gen_expr_inner(&mut self, expression: &Expression, out: &mut String) -> Result<String, CodegenError> {
        match &expression.expr {
            Expr::Int(value) => Ok(format!("g_int({})", self.integer(value, expression.span)?)),
            Expr::Float(value) => Ok(format!("g_float({})", self.float(value))),
            Expr::String(value) => Ok(c_string_value(value)),
            Expr::Bool(value) => Ok(format!("g_bool({})", *value as u8)),
            Expr::Nil => Ok("g_nil()".into()),
            Expr::Var(name) => self.gen_var(name, expression.span),
            Expr::FieldAccess { base, label } => self.gen_field(base, label, expression.span, out),
            Expr::Constructor(reference) => {
                let info = self.constructor(reference, expression.span)?.clone();
                if info.fields.is_empty() {
                    Ok(format!("g_record({}, 0, NULL)", c_string(&reference.name)))
                } else {
                    let name = format!("gleam_ctor_{}", reference.name);
                    Ok(format!("g_function({name}, {})", info.fields.len()))
                }
            }
            Expr::List { elements, spread } => {
                let elements = self.gen_values(elements, out)?;
                let mut current = match spread {
                    Some(rest) => self.gen_expr(rest, out)?,
                    None => "g_list_empty()".into(),
                };
                for element in elements.iter().rev() {
                    let next = self.temp();
                    out.push_str(&format!(
                        "  GValue {next} = g_list_prepend({element}, {current});\n"
                    ));
                    current = next;
                }
                Ok(current)
            }
            Expr::Tuple(elements) => {
                let values = self.gen_values(elements, out)?;
                Ok(self.make_aggregate("g_tuple", &values, out))
            }
            Expr::BitArray(array) => self.gen_bits(
                array,
                expression.span,
                |value| matches!(value.expr, Expr::String(_)),
                Self::gen_expr,
                out,
            ),
            Expr::Call(call) => self.gen_call(call, expression.span, out),
            Expr::Fn(function) => self.gen_closure(function, out),
            Expr::Capture(capture) => self.gen_capture(capture, expression.span, out),
            Expr::RecordUpdate(update) => self.gen_record_update(update, expression.span, out),
            Expr::Case(case) => self.gen_case(case, false, out),
            Expr::Block(statements) => self.gen_block(statements, out),
            Expr::Let(let_) => self.gen_let(&let_.pattern, &let_.value, None, expression.span, out),
            Expr::LetAssert(assert) => self.gen_let(
                &assert.pattern,
                &assert.value,
                assert.message.as_deref(),
                expression.span,
                out,
            ),
            Expr::Assert(assert) => {
                let value = self.gen_expr(&assert.value, out)?;
                self.require_type("G_BOOL", "Bool", &value, out);
                out.push_str(&format!("  if (!({value}).as.boolean) {{\n"));
                self.gen_panic(assert.message.as_deref(), "assertion failed", out)?;
                out.push_str(&format!("  }}\n  g_release({value});\n"));
                Ok("g_nil()".into())
            }
            Expr::Use(use_) => self.gen_use(use_, expression.span, out),
            Expr::EchoPipe => Err(CodegenError::new("`echo` needs a value", expression.span)),
            Expr::Echo(inner) => {
                let value = self.gen_expr(inner, out)?;
                out.push_str(&format!("  g_echo({value}, __FILE__, __LINE__);\n"));
                Ok(value)
            }
            Expr::Todo { message } | Expr::Panic { message } => {
                let fallback = if matches!(expression.expr, Expr::Todo { .. }) {
                    "todo"
                } else {
                    "panic"
                };
                self.gen_panic(message.as_deref(), fallback, out)?;
                Ok("g_nil()".into())
            }
            Expr::Binary { op, lhs, rhs } => self.gen_binary(*op, lhs, rhs, out),
            Expr::Neg(inner) => {
                if let Expr::Int(number) = &inner.expr {
                    let signed = IntValue {
                        raw: format!("-{}", number.raw),
                    };
                    return Ok(format!(
                        "g_int({})",
                        self.integer(&signed, expression.span)?
                    ));
                }
                let value = self.gen_expr(inner, out)?;
                let result = self.temp();
                out.push_str(&format!(
                    "  GValue {result};\n  if (({value}).tag == G_INT) {{ {result} = g_int_from_bits(UINT64_C(0) - (uint64_t)({value}).as.integer); }}\n  else if (({value}).tag == G_FLOAT) {{ {result} = g_float(-({value}).as.floating); }}\n  else g_type_error(\"Int or Float\", {value}, __FILE__, __LINE__);\n  g_release({value});\n"
                ));
                Ok(result)
            }
            Expr::Not(inner) => {
                let value = self.gen_expr(inner, out)?;
                let result = self.temp();
                out.push_str(&format!(
                    "  if (({value}).tag != G_BOOL) g_type_error(\"Bool\", {value}, __FILE__, __LINE__);\n  GValue {result} = g_bool(!({value}).as.boolean);\n  g_release({value});\n"
                ));
                Ok(result)
            }
            Expr::Pipeline { exprs, .. } => self.gen_pipeline(exprs, out),
        }
    }

    fn gen_var(&mut self, name: &str, span: Span) -> Result<String, CodegenError> {
        if let Some(value) = self.visible.get(name) {
            return Ok(format!("g_retain({value})"));
        }
        if let Some(info) = self.functions.get(name) {
            return Ok(format!("g_function({}, {})", info.c_name, info.arity));
        }
        if self.constants.iter().any(|constant| constant == name) {
            return Ok(format!("g_retain(gleam_const_{name})"));
        }
        if let Some((module, name)) = self.unqualified.get(name).cloned() {
            if let Some((function, arity, _)) = std_function(&module, &name) {
                return Ok(self.native_function(function, arity));
            }
        }
        Err(CodegenError::new(
            format!("unknown variable or function `{name}`"),
            span,
        ))
    }

    fn gen_field(
        &mut self,
        base: &Expression,
        label: &str,
        span: Span,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        if let Expr::Var(module) = &base.expr {
            if let Some(path) = self.imports.get(module) {
                if let Some((function, arity, _)) = std_function(path, label) {
                    return Ok(self.native_function(function, arity));
                }
                return Err(CodegenError::new(
                    format!("module `{path}` has no C runtime function `{label}`"),
                    span,
                ));
            } else if is_stdlib_module(module) {
                // Built-in modules may be used without an import.
                if let Some((function, arity, _)) = std_function(module, label) {
                    return Ok(self.native_function(function, arity));
                }
            }
        }
        let value = self.gen_expr(base, out)?;
        let result = self.temp();
        if let Ok(index) = label.parse::<usize>() {
            out.push_str(&format!(
                "  GValue {result} = g_retain(g_tuple_get({value}, {index}));\n"
            ));
        } else {
            let mut candidates: Vec<_> = self
                .constructors
                .iter()
                .filter_map(|(tag, info)| {
                    let index = info.fields.iter().position(|field| {
                        field
                            .label
                            .as_ref()
                            .or(field.name.as_ref())
                            .map(String::as_str)
                            == Some(label)
                    })?;
                    Some((tag, index))
                })
                .collect();
            candidates.sort_unstable();
            if candidates.is_empty() {
                return Err(CodegenError::new(
                    format!("unknown record field `{label}`"),
                    span,
                ));
            }
            out.push_str(&format!("  GValue {result};\n"));
            for (tag, index) in candidates {
                out.push_str(&format!(
                    "  if (g_record_is({value}, {})) {{ {result} = g_retain(g_record_get({value}, {index})); }} else\n",
                    c_string(tag),
                ));
            }
            out.push_str(&format!(
                "  g_panic({}, __FILE__, __LINE__);\n",
                c_string(&format!("record has no field {label}"))
            ));
        }
        out.push_str(&format!("  g_release({value});\n"));
        Ok(result)
    }

    fn native_function(&mut self, function: &str, arity: usize) -> String {
        let id = self.counter;
        self.counter += 1;
        let name = format!("gleam_native_{id}");
        self.extra_functions.push_str(&format!(
            "static GValue {name}(GClosure *closure, GValue *args, size_t argc) {{\n  (void)closure;\n  return {function}(args, argc);\n}}\n\n"
        ));
        format!("g_function({name}, {arity})")
    }

    fn gen_values(&mut self, values: &[Expression], out: &mut String) -> Result<Vec<String>, CodegenError> {
        values.iter().map(|value| self.gen_expr(value, out)).collect()
    }

    fn make_aggregate(&mut self, function: &str, values: &[String], out: &mut String) -> String {
        let result = self.temp();
        if values.is_empty() {
            out.push_str(&format!("  GValue {result} = {function}(0, NULL);\n"));
        } else {
            out.push_str(&format!(
                "  GValue {result} = {function}({}, (GValue[]){{{}}});\n",
                values.len(),
                values.join(", ")
            ));
        }
        result
    }

    /// Compile an expression in tail position. A direct self-recursive call
    /// becomes a tail jump (rebinding the parameters and `goto`-ing the top
    /// of the function loop) instead of a nested C call; anything else is
    /// compiled as usual and yields a value.
    fn gen_expr_tail(
        &mut self,
        expression: &Expression,
        out: &mut String,
    ) -> Result<TailOutcome, CodegenError> {
        match &expression.expr {
            Expr::Block(statements) => {
                let last = statements.len() - 1;
                for statement in &statements[..last] {
                    let value = self.gen_expr(statement, out)?;
                    out.push_str(&format!("  g_release({value});\n"));
                }
                self.gen_expr_tail(&statements[last], out)
            }
            Expr::Case(case) => self.gen_case(case, true, out).map(TailOutcome::Value),
            Expr::Call(call) => {
                if let Some((name, info)) = self.direct_function(&call.fun) {
                    if self.current_fn.as_deref() == Some(name.as_str()) && self.tail_mode {
                        let values = self.eval_call_args(&call.args, &info.labels, out)?;
                        // Release every tracked reference live at this point:
                        // the function parameters, pattern bindings of
                        // enclosing clauses, closure captures, and the
                        // subjects of enclosing cases. The loop re-entry
                        // rebinds them from the new arguments.
                        for scope in &self.scopes {
                            for local in &scope.locals {
                                out.push_str(&format!("  g_release({local});\n"));
                            }
                        }
                        for subjects in &self.live_case_subjects {
                            for subject in subjects {
                                out.push_str(&format!("  g_release({subject});\n"));
                            }
                        }
                        // Transfer ownership of the new arguments to the
                        // parameter bindings (plain aliasing: no retain and
                        // no release — the parameters now own the references).
                        for (parameter, value) in self.param_locals.iter().zip(&values) {
                            out.push_str(&format!("  {parameter} = {value};\n"));
                        }
                        out.push_str("  goto gleam_top;\n");
                        return Ok(TailOutcome::Jumped);
                    }
                }
                let value = self.gen_expr(expression, out)?;
                Ok(TailOutcome::Value(value))
            }
            _ => {
                let value = self.gen_expr(expression, out)?;
                Ok(TailOutcome::Value(value))
            }
        }
    }

    fn gen_block(
        &mut self,
        statements: &[Expression],
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let saved_visible = self.visible.clone();
        self.scopes.push(Scope::default());
        let mut result = "g_nil()".to_string();
        for (index, statement) in statements.iter().enumerate() {
            let value = self.gen_expr(statement, out)?;
            if index + 1 == statements.len() {
                result = value;
            } else {
                out.push_str(&format!("  g_release({value});\n"));
            }
        }
        self.release_scope(out);
        self.visible = saved_visible;
        Ok(result)
    }

    fn gen_panic(
        &mut self,
        message: Option<&Expression>,
        fallback: &str,
        out: &mut String,
    ) -> Result<(), CodegenError> {
        if let Some(message) = message {
            let value = self.gen_expr(message, out)?;
            out.push_str(&format!("  g_panic_value({value}, __FILE__, __LINE__);\n"));
        } else {
            out.push_str(&format!(
                "  g_panic({}, __FILE__, __LINE__);\n",
                c_string(fallback)
            ));
        }
        Ok(())
    }

    fn gen_let(
        &mut self,
        pattern: &Pattern,
        value: &Expression,
        message: Option<&Expression>,
        span: Span,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let value = self.gen_expr(value, out)?;
        let matched = self.temp();
        out.push_str(&format!("  int {matched} = 1;\n"));
        let previous = message.map(|_| self.visible.clone());
        self.gen_pattern(pattern, &value, &matched, span, out)?;
        out.push_str(&format!("  if (!{matched}) {{\n"));
        if let Some(previous) = previous {
            let bindings = std::mem::replace(&mut self.visible, previous);
            self.gen_panic(message, "pattern match failed", out)?;
            self.visible = bindings;
        } else {
            self.gen_panic(None, "pattern match failed", out)?;
        }
        out.push_str("  }\n");
        out.push_str(&format!("  g_release({value});\n"));
        Ok("g_nil()".into())
    }

    fn gen_binary(
        &mut self,
        op: BinOp,
        lhs: &Expression,
        rhs: &Expression,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let left = self.gen_expr(lhs, out)?;
        if matches!(op, BinOp::And | BinOp::Or) {
            out.push_str(&format!(
                "  if (({left}).tag != G_BOOL) g_type_error(\"Bool\", {left}, __FILE__, __LINE__);\n"
            ));
            let result = self.temp();
            let short = if op == BinOp::And { "!" } else { "" };
            out.push_str(&format!(
                "  GValue {result};\n  if ({short}({left}).as.boolean) {{ {result} = g_bool({}); }} else {{\n",
                op == BinOp::Or
            ));
            let right = self.gen_expr(rhs, out)?;
            out.push_str(&format!(
                "    if (({right}).tag != G_BOOL) g_type_error(\"Bool\", {right}, __FILE__, __LINE__);\n    {result} = g_bool(({right}).as.boolean);\n    g_release({right});\n  }}\n  g_release({left});\n"
            ));
            return Ok(result);
        }
        let right = self.gen_expr(rhs, out)?;
        let result = self.temp();
        let line = match op {
            BinOp::Eq | BinOp::NotEq => format!(
                "GValue {result} = g_bool({}g_equal({left}, {right}));",
                if op == BinOp::NotEq { "!" } else { "" }
            ),
            BinOp::Concat => format!("GValue {result} = g_string_concat({left}, {right});"),
            BinOp::Slash => format!("GValue {result} = g_int_divide({left}, {right});"),
            BinOp::Percent => format!("GValue {result} = g_int_modulo({left}, {right});"),
            BinOp::Lt | BinOp::Gt | BinOp::LtEq | BinOp::GtEq => {
                self.require_type("G_INT", "Int", &left, out);
                self.require_type("G_INT", "Int", &right, out);
                let operator = match op {
                    BinOp::Lt => "<",
                    BinOp::Gt => ">",
                    BinOp::LtEq => "<=",
                    _ => ">=",
                };
                format!("GValue {result} = g_bool(({left}).as.integer {operator} ({right}).as.integer);")
            }
            BinOp::LtFloat | BinOp::GtFloat | BinOp::LtEqFloat | BinOp::GtEqFloat => {
                self.require_type("G_FLOAT", "Float", &left, out);
                self.require_type("G_FLOAT", "Float", &right, out);
                let operator = match op {
                    BinOp::LtFloat => "<",
                    BinOp::GtFloat => ">",
                    BinOp::LtEqFloat => "<=",
                    _ => ">=",
                };
                format!("GValue {result} = g_bool(({left}).as.floating {operator} ({right}).as.floating);")
            }
            BinOp::Plus | BinOp::Minus | BinOp::Times => {
                self.require_type("G_INT", "Int", &left, out);
                self.require_type("G_INT", "Int", &right, out);
                let operator = match op {
                    BinOp::Plus => "+",
                    BinOp::Minus => "-",
                    _ => "*",
                };
                format!("GValue {result} = g_int_from_bits((uint64_t)({left}).as.integer {operator} (uint64_t)({right}).as.integer);")
            }
            BinOp::PlusFloat | BinOp::MinusFloat | BinOp::TimesFloat | BinOp::SlashFloat => {
                self.require_type("G_FLOAT", "Float", &left, out);
                self.require_type("G_FLOAT", "Float", &right, out);
                let operator = match op {
                    BinOp::PlusFloat => "+",
                    BinOp::MinusFloat => "-",
                    BinOp::TimesFloat => "*",
                    _ => "/",
                };
                if op == BinOp::SlashFloat {
                    format!("GValue {result} = g_float(({right}).as.floating == 0.0 ? 0.0 : ({left}).as.floating / ({right}).as.floating);")
                } else {
                    format!("GValue {result} = g_float(({left}).as.floating {operator} ({right}).as.floating);")
                }
            }
            BinOp::And | BinOp::Or => unreachable!(),
        };
        out.push_str(&format!("  {line}\n  g_release({left});\n  g_release({right});\n"));
        Ok(result)
    }

    fn require_type(&self, tag: &str, name: &str, value: &str, out: &mut String) {
        out.push_str(&format!(
            "  if (({value}).tag != {tag}) g_type_error(\"{name}\", {value}, __FILE__, __LINE__);\n"
        ));
    }

    fn gen_call(&mut self, call: &Call, span: Span, out: &mut String) -> Result<String, CodegenError> {
        if let Expr::Constructor(reference) = &call.fun.expr {
            let info = self.constructor(reference, span)?.clone();
            let values = self.eval_call_args(&call.args, &info.labels(), out)?;
            let result = self.make_record(&reference.name, &values, out);
            return Ok(result);
        }
        if let Expr::FieldAccess { base, label } = &call.fun.expr {
            if matches!(&base.expr, Expr::Var(_)) && label.starts_with(|c: char| c.is_ascii_uppercase()) {
                let reference = ConstructorRef {
                    module: None,
                    name: label.clone(),
                };
                let info = self.constructor(&reference, span)?.clone();
                let values = self.eval_call_args(&call.args, &info.labels(), out)?;
                return Ok(self.make_record(label, &values, out));
            }
        }

        if let Some((name, info)) = self.direct_function(&call.fun) {
            let values = self.eval_call_args(&call.args, &info.labels, out)?;
            let result = self.temp();
            let arguments = c_arguments(&values);
            if name.starts_with("gleam_fn_") {
                out.push_str(&format!(
                    "  GValue {result} = {name}(NULL, {arguments}, {});\n",
                    values.len()
                ));
            } else {
                out.push_str(&format!(
                    "  GValue {result} = {name}({arguments}, {});\n",
                    values.len()
                ));
            }
            for value in values {
                out.push_str(&format!("  g_release({value});\n"));
            }
            return Ok(result);
        }

        let function = self.gen_expr(&call.fun, out)?;
        let values = self.eval_call_args(&call.args, &vec![None; call.args.len()], out)?;
        let result = self.temp();
        out.push_str(&format!(
            "  GValue {result} = g_call({function}, {}, {});\n  g_release({function});\n",
            c_arguments(&values),
            values.len()
        ));
        for value in values {
            out.push_str(&format!("  g_release({value});\n"));
        }
        Ok(result)
    }

    fn direct_function(&self, expression: &Expression) -> Option<(String, FunctionInfo)> {
        match &expression.expr {
            Expr::Var(name) if !self.visible.contains_key(name) => {
                if let Some(info) = self.functions.get(name) {
                    return Some((info.c_name.clone(), info.clone()));
                }
                let (module, name) = self.unqualified.get(name)?;
                let (function, arity, labels) = std_function(module, name)?;
                Some((
                    function.into(),
                    FunctionInfo {
                        c_name: function.into(),
                        arity,
                        labels: labels
                            .iter()
                            .map(|label| label.map(|l| l.to_string()))
                            .collect(),
                    },
                ))
            }
            Expr::FieldAccess { base, label } => {
                let Expr::Var(module) = &base.expr else { return None };
                let function = if let Some(path) = self.imports.get(module) {
                    std_function(path, label)
                } else {
                    // Built-in modules may be used without an import.
                    is_stdlib_module(module).then(|| std_function(module, label))
                        .flatten()
                };
                let (function, arity, labels) = function?;
                Some((
                    function.into(),
                    FunctionInfo {
                        c_name: function.into(),
                        arity,
                        labels: labels
                            .iter()
                            .map(|label| label.map(|l| l.to_string()))
                            .collect(),
                    },
                ))
            }
            _ => None,
        }
    }

    fn eval_call_args(
        &mut self,
        args: &[CallArg],
        labels: &[Option<String>],
        out: &mut String,
    ) -> Result<Vec<String>, CodegenError> {
        let mut evaluated = Vec::new();
        for arg in args {
            match arg {
                CallArg::Value(value) => {
                    let value = self.gen_expr(value, out)?;
                    evaluated.push((None, value));
                }
                CallArg::Labelled { label, value } => {
                    let value = self.gen_expr(value, out)?;
                    evaluated.push((Some(label.clone()), value));
                }
            }
        }
        order_arguments(evaluated, labels, Span::point(0))
    }

    fn make_record(&mut self, tag: &str, values: &[String], out: &mut String) -> String {
        let result = self.temp();
        out.push_str(&format!(
            "  GValue {result} = g_record({}, {}, {});\n",
            c_string(tag),
            values.len(),
            c_arguments(values)
        ));
        result
    }

    fn gen_pipeline(&mut self, exprs: &[Expression], out: &mut String) -> Result<String, CodegenError> {
        let mut value = self.gen_expr(&exprs[0], out)?;
        for stage in &exprs[1..] {
            let next = match &stage.expr {
                Expr::EchoPipe => {
                    out.push_str(&format!("  g_echo({value}, __FILE__, __LINE__);\n"));
                    continue;
                }
                Expr::Call(call) => self.gen_pipeline_call(call, &value, stage.span, out)?,
                _ => {
                    let function = self.gen_expr(stage, out)?;
                    let result = self.temp();
                    out.push_str(&format!(
                        "  GValue {result} = g_call({function}, (GValue[]){{{value}}}, 1);\n  g_release({function});\n"
                    ));
                    result
                }
            };
            out.push_str(&format!("  g_release({value});\n"));
            value = next;
        }
        Ok(value)
    }

    fn gen_pipeline_call(
        &mut self,
        call: &Call,
        value: &str,
        span: Span,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let arity = match &call.fun.expr {
            Expr::Constructor(reference) => Some(self.constructor(reference, span)?.fields.len()),
            _ => self.direct_function(&call.fun).map(|(_, info)| info.arity),
        };
        let result = self.temp();
        match arity {
            Some(arity) if arity == call.args.len() => {
                let function = self.gen_call(call, span, out)?;
                out.push_str(&format!(
                    "  GValue {result} = g_call({function}, (GValue[]){{{value}}}, 1);\n  g_release({function});\n"
                ));
                Ok(result)
            }
            Some(_) => {
                let name = format!("${result}");
                self.visible.insert(name.clone(), value.into());
                let mut call = call.clone();
                call.args.insert(
                    0,
                    CallArg::Value(Expression::synthetic(Expr::Var(name.clone()))),
                );
                let generated = self.gen_call(&call, span, out);
                self.visible.remove(&name);
                generated
            }
            None => {
                let function = self.gen_expr(&call.fun, out)?;
                let args = self.eval_call_args(&call.args, &vec![None; call.args.len()], out)?;
                let mut with_piped = vec![value.to_owned()];
                with_piped.extend(args.iter().cloned());
                let argc = args.len();
                out.push_str(&format!(
                    "  GValue {result};\n  if (g_arity({function}) == {argc}) {{\n    GValue next = g_call({function}, {}, {argc});\n    {result} = g_call(next, (GValue[]){{{value}}}, 1);\n    g_release(next);\n  }} else {{\n    {result} = g_call({function}, {}, {});\n  }}\n  g_release({function});\n",
                    c_arguments(&args), c_arguments(&with_piped), with_piped.len(),
                ));
                for arg in &args {
                    out.push_str(&format!("  g_release({arg});\n"));
                }
                Ok(result)
            }
        }
    }

    fn gen_case(
        &mut self,
        case: &Case,
        tail: bool,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let subjects = self.gen_values(&case.subjects, out)?;
        let result = self.temp();
        out.push_str(&format!(
            "  GValue {result};\n  int {result}_matched = 0;\n"
        ));
        if tail {
            self.live_case_subjects.push(subjects.clone());
        }
        for clause in &case.clauses {
            for patterns in clause.pattern_groups() {
                let saved_visible = self.visible.clone();
                let matched = self.temp();
                out.push_str(&format!(
                    "  if (!{result}_matched) {{\n  int {matched} = 1;\n"
                ));
                self.scopes.push(Scope::default());
                for (pattern, subject) in patterns.iter().zip(&subjects) {
                    self.gen_pattern(pattern, subject, &matched, clause.span, out)?;
                }
                if let Some(guard) = &clause.guard {
                    out.push_str(&format!("  if ({matched}) {{\n"));
                    let guard = self.gen_expr(&guard.to_expression(clause.span), out)?;
                    out.push_str(&format!(
                        "  {matched} = ({guard}).as.boolean;\n  g_release({guard});\n  }}\n",
                    ));
                }
                out.push_str(&format!("  if ({matched}) {{\n"));
                self.scopes.push(Scope::default());
                let outcome = if tail {
                    self.gen_expr_tail(&clause.expression, out)?
                } else {
                    TailOutcome::Value(self.gen_expr(&clause.expression, out)?)
                };
                if let TailOutcome::Value(value) = outcome {
                    out.push_str(&format!("  {result} = {value};\n  {result}_matched = 1;\n"));
                }
                self.release_scope(out);
                out.push_str("  }\n");
                self.release_scope(out);
                out.push_str("  }\n");
                self.visible = saved_visible;
            }
        }
        if tail {
            self.live_case_subjects.pop();
        }
        out.push_str(&format!(
            "  if (!{result}_matched) g_panic(\"no case clause matched\", __FILE__, __LINE__);\n"
        ));
        for subject in &subjects {
            out.push_str(&format!("  g_release({subject});\n"));
        }
        Ok(result)
    }

    fn gen_bits<T>(
        &mut self,
        array: &BitArray<T>,
        span: Span,
        value_expression: impl Fn(&T) -> bool,
        mut compile_value: impl FnMut(&mut Self, &T, &mut String) -> Result<String, CodegenError>,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let builder = self.temp();
        out.push_str(&format!("  GBitBuilder {builder} = {{0}};\n"));
        for segment in &array.segments {
            let options = SegmentOptions::parse(&segment.options, value_expression(&segment.value))
                .map_err(|message| CodegenError::new(message, span))?;
            let value = compile_value(self, &segment.value, out)?;
            self.append_bit_segment(&builder, &value, &options, out)?;
            out.push_str(&format!("  g_release({value});\n"));
        }
        Ok(format!("g_bits_finish(&{builder})"))
    }

    fn append_bit_segment(
        &mut self,
        builder: &str,
        value: &str,
        options: &SegmentOptions<'_>,
        out: &mut String,
    ) -> Result<(), CodegenError> {
        let size = self.bit_size(options, out)?;
        out.push_str(&format!(
            "  g_bits_append(&{builder}, {value}, {}, {}, {size}, {});\n",
            options.kind.c_name(),
            options.endian,
            options.unit,
        ));
        Ok(())
    }

    fn bit_size(
        &mut self,
        options: &SegmentOptions<'_>,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        match options.size {
            Some(size) => self.gen_expr(size, out),
            None => Ok("g_nil()".into()),
        }
    }

    fn gen_bit_pattern(
        &mut self,
        array: &BitArray<Pattern>,
        value: &str,
        matched: &str,
        span: Span,
        out: &mut String,
    ) -> Result<(), CodegenError> {
        let offset = self.temp();
        out.push_str(&format!("  size_t {offset} = 0;\n"));
        for segment in &array.segments {
            let text = matches!(segment.value, Pattern::String(_));
            let options = SegmentOptions::parse(&segment.options, text)
                .map_err(|message| CodegenError::new(message, span))?;
            if let (SegmentKind::Text(_), Pattern::String(text)) = (options.kind, &segment.value) {
                out.push_str(&format!("  if ({matched}) {{\n"));
                let builder = self.temp();
                let string = self.temp();
                let prefix = self.temp();
                out.push_str(&format!(
                    "  GBitBuilder {builder} = {{0}};\n  GValue {string} = {};\n",
                    c_string_value(text),
                ));
                self.append_bit_segment(&builder, &string, &options, out)?;
                out.push_str(&format!(
                    "  GValue {prefix} = g_bits_finish(&{builder});\n  {matched} = g_bits_prefix({value}, &{offset}, {prefix});\n  g_release({prefix});\n  g_release({string});\n  }}\n",
                ));
                continue;
            }
            let part = self.temp();
            out.push_str(&format!(
                "  GValue {part} = g_nil();\n  if ({matched}) {{\n"
            ));
            let size = self.bit_size(&options, out)?;
            out.push_str(&format!(
                "  {matched} = g_bits_take({value}, &{offset}, {}, {}, {size}, {}, {}, &{part});\n  }}\n",
                options.kind.c_name(), options.endian, options.unit, u8::from(options.signed),
            ));
            self.gen_pattern(&segment.value, &part, matched, span, out)?;
            out.push_str(&format!("  g_release({part});\n"));
        }
        pattern_test(matched, &format!("g_bits_end({value}, {offset})"), out);
        Ok(())
    }

    fn gen_pattern(
        &mut self,
        pattern: &Pattern,
        value: &str,
        matched: &str,
        span: Span,
        out: &mut String,
    ) -> Result<(), CodegenError> {
        match pattern {
            Pattern::Var(name) => {
                self.bind(
                    name,
                    format!("{matched} ? g_retain({value}) : g_nil()"),
                    out,
                );
            }
            Pattern::Discard(_) => {}
            Pattern::Int(expected) => pattern_test(
                matched,
                &format!(
                    "({value}).tag == G_INT && ({value}).as.integer == {}",
                    self.integer(expected, span)?
                ),
                out,
            ),
            Pattern::Float(expected) => pattern_test(
                matched,
                &format!(
                    "({value}).tag == G_FLOAT && ({value}).as.floating == {}",
                    self.float(expected)
                ),
                out,
            ),
            Pattern::String(expected) => pattern_test(
                matched,
                &format!(
                    "g_string_equals_n({value}, {}, {})",
                    c_string(expected),
                    expected.len()
                ),
                out,
            ),
            Pattern::Bool(expected) => pattern_test(
                matched,
                &format!(
                    "({value}).tag == G_BOOL && ({value}).as.boolean == {}",
                    u8::from(*expected)
                ),
                out,
            ),
            Pattern::Nil => pattern_test(matched, &format!("({value}).tag == G_NIL"), out),
            Pattern::StringPrefix {
                prefix,
                prefix_alias,
                rest,
            } => {
                pattern_test(
                    matched,
                    &format!(
                        "g_string_starts_with_n({value}, {}, {})",
                        c_string(prefix),
                        prefix.len()
                    ),
                    out,
                );
                if let Some(name) = prefix_alias {
                    self.bind(
                        name,
                        format!("{matched} ? {} : g_nil()", c_string_value(prefix)),
                        out,
                    );
                }
                let rest_value = self.temp();
                out.push_str(&format!(
                    "  GValue {rest_value} = {matched} ? g_string_drop_prefix({value}, {}) : g_nil();\n",
                    prefix.len()
                ));
                self.gen_pattern(rest, &rest_value, matched, span, out)?;
                out.push_str(&format!("  g_release({rest_value});\n"));
            }
            Pattern::Constructor(reference, args) => {
                let info = self.constructor(reference, span)?.clone();
                pattern_test(
                    matched,
                    &format!("g_record_is({value}, {})", c_string(&reference.name)),
                    out,
                );
                let mut position = 0;
                for arg in args {
                    let (index, pattern) = match arg {
                        PatternArg::Named { label, pattern } => {
                            let index = info
                                .fields
                                .iter()
                                .position(|field| {
                                    field.label.as_ref().or(field.name.as_ref()) == Some(label)
                                })
                                .ok_or_else(|| {
                                    CodegenError::new(format!("unknown field `{label}`"), span)
                                })?;
                            (index, pattern)
                        }
                        PatternArg::Unnamed(pattern) => {
                            let index = position;
                            position += 1;
                            (index, pattern)
                        }
                        PatternArg::DiscardRest => continue,
                    };
                    self.gen_pattern(
                        pattern,
                        &format!("g_record_get({value}, {index})"),
                        matched,
                        span,
                        out,
                    )?;
                }
            }
            Pattern::List { elements, rest } => {
                let op = if rest.is_some() { ">=" } else { "==" };
                pattern_test(
                    matched,
                    &format!("(({value}).tag == G_NIL || ({value}).tag == G_LIST) && g_list_length({value}) {op} {}", elements.len()),
                    out,
                );
                for (index, element) in elements.iter().enumerate() {
                    self.gen_pattern(element, &list_item(value, index), matched, span, out)?;
                }
                if let Some(rest) = rest {
                    self.gen_pattern(rest, &list_tail(value, elements.len()), matched, span, out)?;
                }
            }
            Pattern::Tuple(elements) => {
                pattern_test(
                    matched,
                    &format!("({value}).tag == G_TUPLE && ((GTuple *)({value}).as.pointer)->length == {}", elements.len()),
                    out,
                );
                for (index, element) in elements.iter().enumerate() {
                    self.gen_pattern(
                        element,
                        &format!("g_tuple_get({value}, {index})"),
                        matched,
                        span,
                        out,
                    )?;
                }
            }
            Pattern::BitArray(array) => self.gen_bit_pattern(array, value, matched, span, out)?,
            Pattern::Alias { pattern, name } => {
                self.gen_pattern(pattern, value, matched, span, out)?;
                self.bind(
                    name,
                    format!("{matched} ? g_retain({value}) : g_nil()"),
                    out,
                );
            }
            Pattern::Alternative(_) => {
                return Err(CodegenError::new(
                    "alternative patterns require a case clause",
                    span,
                ))
            }
        }
        Ok(())
    }

    fn bind(&mut self, name: &str, value: String, out: &mut String) {
        let variable = self.temp();
        out.push_str(&format!("  GValue {variable} = {value};\n"));
        self.visible.insert(name.into(), variable.clone());
        self.scopes.last_mut().unwrap().locals.push(variable);
    }

    fn constructor(
        &self,
        reference: &ConstructorRef,
        span: Span,
    ) -> Result<&ConstructorInfo, CodegenError> {
        self.constructors.get(&reference.name).ok_or_else(|| {
            CodegenError::new(format!("unknown constructor `{}`", reference.name), span)
        })
    }

    fn gen_record_update(&mut self, update: &RecordUpdate, span: Span, out: &mut String) -> Result<String, CodegenError> {
        let info = self.constructor(&update.constructor, span)?.clone();
        let base = self.gen_expr(&update.base, out)?;
        out.push_str(&format!(
            "  if (!g_record_is({base}, {})) g_panic(\"record update has the wrong constructor\", __FILE__, __LINE__);\n",
            c_string(&update.constructor.name),
        ));
        let mut replacements = HashMap::new();
        for arg in &update.args {
            let CallArg::Labelled { label, value } = arg else {
                return Err(CodegenError::new("record updates require labelled fields", span));
            };
            let index = info.fields.iter().position(|field| {
                field.label.as_ref().or(field.name.as_ref()).map(String::as_str) == Some(label)
            }).ok_or_else(|| CodegenError::new(format!("unknown field `{label}`"), span))?;
            let value = self.gen_expr(value, out)?;
            replacements.insert(index, value);
        }
        let values: Vec<String> = (0..info.fields.len())
            .map(|index| {
                replacements.remove(&index).unwrap_or_else(|| {
                    format!("g_retain(g_record_get({base}, {index}))")
                })
            })
            .collect();
        let result = self.make_record(&update.constructor.name, &values, out);
        out.push_str(&format!("  g_release({base});\n"));
        for value in replacements.into_values() {
            out.push_str(&format!("  g_release({value});\n"));
        }
        Ok(result)
    }

    fn gen_use(
        &mut self,
        use_: &Use,
        span: Span,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let mut args = Vec::with_capacity(use_.patterns.len());
        let mut statements = Vec::with_capacity(use_.patterns.len() + 1);
        for (index, pattern) in use_.patterns.iter().enumerate() {
            let arg = format!("$use_{index}");
            statements.push(Expression::synthetic(Expr::Let(Let {
                pattern: pattern.clone(),
                value: Box::new(Expression::synthetic(Expr::Var(arg.clone()))),
                annotation: None,
            })));
            args.push(arg);
        }
        statements.push((*use_.body).clone());
        let callback = Expression {
            span,
            expr: Expr::Fn(FnLiteral {
                args,
                annotations: Vec::new(),
                return_annotation: None,
                body: Box::new(Expression::synthetic(Expr::Block(statements))),
            }),
        };
        let mut call = match &use_.call.expr {
            Expr::Call(call) => call.clone(),
            _ => Call {
                fun: use_.call.clone(),
                fun_span: use_.call.span,
                args: Vec::new(),
            },
        };
        call.args.push(CallArg::Value(callback));
        self.gen_call(&call, span, out)
    }

    fn gen_closure(&mut self, function: &FnLiteral, _out: &mut String) -> Result<String, CodegenError> {
        let mut captures: Vec<(String, String)> = self
            .visible
            .iter()
            .map(|(name, value)| (name.clone(), value.clone()))
            .collect();
        captures.sort_by(|left, right| left.0.cmp(&right.0));
        let id = self.counter;
        self.counter += 1;
        let name = format!("gleam_lambda_{id}");
        let saved_visible = std::mem::take(&mut self.visible);
        let saved_scopes = std::mem::take(&mut self.scopes);
        self.scopes.push(Scope::default());
        let mut body = format!(
            "static GValue {name}(GClosure *closure, GValue *args, size_t argc) {{\n  if (argc != {}) g_panic(\"incorrect argument count\", __FILE__, __LINE__);\n",
            function.args.len()
        );
        for (index, (variable, _)) in captures.iter().enumerate() {
            let value = self.temp();
            body.push_str(&format!(
                "  GValue {value} = g_retain(closure->captures[{index}]);\n"
            ));
            self.visible.insert(variable.clone(), value.clone());
            self.scopes.last_mut().unwrap().locals.push(value);
        }
        for (index, argument) in function.args.iter().enumerate() {
            if !argument.starts_with('_') {
                let value = self.temp();
                body.push_str(&format!("  GValue {value} = g_retain(args[{index}]);\n"));
                self.visible.insert(argument.clone(), value.clone());
                self.scopes.last_mut().unwrap().locals.push(value);
            }
        }
        let result = self.gen_expr(&function.body, &mut body)?;
        body.push_str(&format!("  GValue gleam_return = {result};\n"));
        self.release_scope(&mut body);
        body.push_str("  return gleam_return;\n}\n\n");
        self.extra_functions.push_str(&body);
        self.visible = saved_visible;
        self.scopes = saved_scopes;
        let retained: Vec<String> = captures.iter().map(|(_, value)| format!("g_retain({value})")).collect();
        Ok(format!(
            "g_closure_new({name}, {}, {}, {})",
            function.args.len(),
            retained.len(),
            c_arguments(&retained)
        ))
    }

    fn gen_capture(
        &mut self,
        capture: &Capture,
        span: Span,
        out: &mut String,
    ) -> Result<String, CodegenError> {
        let name = "$capture".to_string();
        let parameter = || Expression::synthetic(Expr::Var(name.clone()));
        let args = capture
            .args
            .iter()
            .map(|arg| match arg {
                CaptureArg::Value(value) => CallArg::Value(value.clone()),
                CaptureArg::Labelled { label, value } => CallArg::Labelled {
                    label: label.clone(),
                    value: value.clone(),
                },
                CaptureArg::Placeholder => CallArg::Value(parameter()),
                CaptureArg::LabelledPlaceholder(label) => CallArg::Labelled {
                    label: label.clone(),
                    value: parameter(),
                },
            })
            .collect();
        let body = Expression {
            span,
            expr: Expr::Call(Call {
                fun: capture.fun.clone(),
                args,
                fun_span: capture.fun.span,
            }),
        };
        self.gen_closure(
            &FnLiteral {
                args: vec![name],
                annotations: Vec::new(),
                return_annotation: None,
                body: Box::new(body),
            },
            out,
        )
    }

    fn integer(&self, value: &IntValue, span: Span) -> Result<String, CodegenError> {
        let (negative, magnitude) = match value.raw.strip_prefix('-') {
            Some(raw) => (true, IntValue { raw: raw.into() }.as_u64()),
            None => (false, value.as_u64()),
        };
        match (negative, magnitude) {
            (true, Some(n)) if n == 1 << 63 => Ok("INT64_MIN".into()),
            (_, Some(n)) if n <= i64::MAX as u64 => {
                let sign = if negative { "-" } else { "" };
                Ok(format!("({sign}INT64_C({n}))"))
            }
            _ => Err(CodegenError::new(
                "integer does not fit in a C int64_t",
                span,
            )),
        }
    }

    fn float(&self, value: &FloatValue) -> String {
        value.raw.replace('_', "")
    }
}

impl ConstructorInfo {
    fn labels(&self) -> Vec<Option<String>> {
        self.fields
            .iter()
            .map(|field| field.label.clone().or_else(|| field.name.clone()))
            .collect()
    }
}

